BASE_FONT_OFFSET = 4  # global readability bump (+4pt on all fonts)

def F(sz: int, bold: bool = False) -> QFont:
    f = QFont("Courier New", sz + BASE_FONT_OFFSET)
    f.setBold(bold)
    return f


